<?php

namespace App\Http\Controllers;

use App\Models\Order;
use App\Models\Payment;
use App\Services\PayWayService;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;
use Throwable;

class PayWayPaymentController extends Controller
{
    public function show(Payment $payment)
    {
        $this->ensureCustomerOwnsPayment($payment);
        abort_unless($payment->provider === 'aba_payway', 404);

        if ($payment->status === 'paid') {
            return redirect()->route('web.payments.success', $payment->id);
        }

        return view('website.payments.aba-qr', compact('payment'));
    }

    public function status(Payment $payment, PayWayService $payWay): JsonResponse
    {
        $this->ensureCustomerOwnsPayment($payment);

        if ($payment->provider === 'aba_payway' && $payment->status === 'pending' && $payment->tran_id) {
            try {
                $this->verifyAndSynchronize($payment, $payWay);
            } catch (Throwable $exception) {
                // Keep the screen usable while ABA is temporarily unavailable.
                Log::notice('ABA PayWay polling check could not complete.', [
                    'payment_id' => $payment->id,
                    'message' => $exception->getMessage(),
                ]);
            }
        }

        $payment->refresh();
        $order = $payment->order()->first();

        return response()->json([
            'status' => $payment->status,
            'order_status' => $order?->order_status ?? 'pending',
            'paid' => $payment->status === 'paid',
            'order_url' => route('web.orders.show', $payment->order_id),
            'success_url' => route('web.payments.success', $payment->id),
        ])->header('Cache-Control', 'no-store, no-cache, must-revalidate, max-age=0')
          ->header('Pragma', 'no-cache');
    }


    /** Show an ABA QR generated by the staff POS. */
    public function showForStaff(Payment $payment)
    {
        $this->ensureStaffOwnsPosPayment($payment);
        abort_unless($payment->provider === 'aba_payway', 404);

        if ($payment->status === 'paid') {
            return redirect()->route('pos.payments.success', $payment->id);
        }

        return view('pos.payments.aba-qr', compact('payment'));
    }

    /** Dedicated success receipt for a verified customer website payment. */
    public function success(Payment $payment)
    {
        $this->ensureCustomerOwnsPayment($payment);
        abort_unless($payment->provider === 'aba_payway', 404);

        if ($payment->status !== 'paid') {
            return redirect()->route('web.payments.show', $payment->id)
                ->with('error', 'This payment has not been verified yet.');
        }

        $payment->loadMissing(['order.customer', 'order.orderItems.product', 'order.orderType', 'order.paymentMethod']);

        return view('website.payments.success', compact('payment'));
    }

    /** Dedicated success receipt for a verified staff POS payment. */
    public function successForStaff(Payment $payment)
    {
        $this->ensureStaffOwnsPosPayment($payment);
        abort_unless($payment->provider === 'aba_payway', 404);

        if ($payment->status !== 'paid') {
            return redirect()->route('pos.payments.show', $payment->id)
                ->with('error', 'This payment has not been verified yet.');
        }

        $payment->loadMissing(['order.customer', 'order.orderItems.product', 'order.orderType', 'order.paymentMethod']);

        return view('pos.payments.success', compact('payment'));
    }

    /** Poll and verify a staff POS payment against ABA Check Transaction API. */
    public function statusForStaff(Payment $payment, PayWayService $payWay): JsonResponse
    {
        $this->ensureStaffOwnsPosPayment($payment);

        if ($payment->provider === 'aba_payway' && $payment->status === 'pending' && $payment->tran_id) {
            try {
                $this->verifyAndSynchronize($payment, $payWay);
            } catch (Throwable $exception) {
                Log::notice('ABA POS payment polling check could not complete.', [
                    'payment_id' => $payment->id,
                    'message' => $exception->getMessage(),
                ]);
            }
        }

        $payment->refresh();

        $statusMessages = [
            'pending' => 'Waiting for ABA to confirm the payment. The server checks the transaction automatically.',
            'paid' => 'Payment verified successfully by ABA.',
            'failed' => 'ABA did not approve this payment. Please check the order before trying again.',
            'declined' => 'The payment was declined by ABA.',
            'cancelled' => 'The payment was cancelled.',
            'expired' => 'The payment QR has expired. Create a new payment attempt.',
            'review_required' => 'ABA reported a payment result that could not be matched safely to this order. Ask an administrator to reconcile it.',
        ];

        return response()->json([
            'status' => $payment->status,
            'paid' => $payment->status === 'paid',
            'message' => $statusMessages[$payment->status] ?? 'Payment status: '.$payment->status,
            'checked_at' => now()->toIso8601String(),
            'order_url' => $this->staffOrdersUrl(),
            'success_url' => route('pos.payments.success', $payment->id),
        ])->header('Cache-Control', 'no-store, no-cache, must-revalidate, max-age=0')
          ->header('Pragma', 'no-cache');
    }

    /** Public endpoint called by ABA. A callback is only a notification; status is confirmed by Check Transaction. */
    public function callback(Request $request, PayWayService $payWay): JsonResponse
    {
        $payload = $request->all();
        $transactionId = (string) ($payload['tran_id'] ?? '');

        if ($transactionId === '') {
            return response()->json(['message' => 'accepted'], 200);
        }

        $payment = Payment::query()->where('provider', 'aba_payway')->where('tran_id', $transactionId)->first();
        if (! $payment) {
            Log::warning('ABA callback received for an unknown transaction.', ['tran_id' => $transactionId]);
            return response()->json(['message' => 'accepted'], 200);
        }

        $payment->callback_payload = $payload;
        $payment->save();

        // ABA QR callbacks normally carry status=0. We still ask the Check Transaction API
        // before changing the order to paid; never trust a browser or callback body alone.
        if ((string) ($payload['status'] ?? '') === '0' && $payment->status !== 'paid') {
            try {
                $this->verifyAndSynchronize($payment, $payWay);
            } catch (Throwable $exception) {
                Log::warning('ABA callback received; authoritative status check will be retried by the payment status page.', [
                    'payment_id' => $payment->id,
                    'message' => $exception->getMessage(),
                ]);
            }
        }

        return response()->json(['message' => 'accepted'], 200);
    }

    private function verifyAndSynchronize(Payment $payment, PayWayService $payWay): bool
    {
        $response = $payWay->checkTransaction((string) $payment->tran_id);
        $data = data_get($response, 'data', []);
        $data = is_array($data) ? $data : (array) $data;
        $providerStatus = strtoupper(trim((string) ($data['payment_status'] ?? '')));
        $providerStatusCode = trim((string) ($data['payment_status_code'] ?? ''));

        // ABA's Check Transaction endpoint returns an outer API status and a
        // separate transaction status inside data. PayWayService has already
        // validated the outer status.code (00/0). Do not confuse that API
        // response code with the transaction's payment_status_code.
        $approvedCodeIsValid = $providerStatusCode === '' || in_array($providerStatusCode, ['0', '00'], true);

        if ($providerStatus === 'APPROVED' && $approvedCodeIsValid) {
            // For KHQR, ABA distinguishes the merchant's original QR amount
            // from the amount/currency the payer actually used. Compare the
            // order with original_amount first; payment_amount may be converted
            // to the payer's currency by the issuing bank.
            if (array_key_exists('original_amount', $data) && $data['original_amount'] !== null) {
                $providerAmount = $data['original_amount'];
                $providerCurrency = strtoupper((string) ($data['original_currency'] ?? $payment->currency));
            } elseif (array_key_exists('total_amount', $data) && $data['total_amount'] !== null) {
                $providerAmount = $data['total_amount'];
                $providerCurrency = strtoupper((string) ($data['original_currency'] ?? $payment->currency));
            } else {
                $providerAmount = $data['payment_amount'] ?? null;
                $providerCurrency = strtoupper((string) ($data['payment_currency'] ?? $payment->currency));
            }

            $expectedAmount = (float) $payment->amount;
            $expectedCurrency = strtoupper((string) $payment->currency);
            $amountMatches = $providerAmount !== null
                && is_numeric($providerAmount)
                && abs((float) $providerAmount - $expectedAmount) <= 0.005;
            $currencyMatches = $providerCurrency === $expectedCurrency;

            if (! $amountMatches || ! $currencyMatches) {
                $payment->update(['status' => 'review_required']);
                Log::alert('ABA payment amount or currency does not match the stored order.', [
                    'payment_id' => $payment->id,
                    'tran_id' => $payment->tran_id,
                    'expected_amount' => $expectedAmount,
                    'provider_amount' => $providerAmount,
                    'expected_currency' => $expectedCurrency,
                    'provider_currency' => $providerCurrency,
                    'payment_amount' => $data['payment_amount'] ?? null,
                    'payment_currency' => $data['payment_currency'] ?? null,
                ]);
                return false;
            }

            $synchronized = DB::transaction(function () use ($payment, $data) {
                // Lock payment then order, matching the cancellation/status workflow lock order.
                $lockedPayment = Payment::query()->lockForUpdate()->findOrFail($payment->id);
                $order = Order::query()->lockForUpdate()->findOrFail($lockedPayment->order_id);

                if ($lockedPayment->status === 'paid') {
                    return true;
                }

                // A delayed provider approval after a staff cancellation must not silently
                // resurrect a cancelled order. Preserve evidence for manual reconciliation.
                if ($order->order_status === 'cancelled' || $lockedPayment->status === 'cancelled') {
                    $lockedPayment->update(['status' => 'review_required']);
                    Log::alert('ABA approved a transaction linked to a cancelled Coffee Corner order; manual review is required.', [
                        'payment_id' => $lockedPayment->id,
                        'order_id' => $order->order_id,
                        'tran_id' => $lockedPayment->tran_id,
                    ]);
                    return false;
                }

                $lockedPayment->update([
                    'status' => 'paid',
                    'apv' => $data['apv'] ?? $lockedPayment->apv,
                    'bank_ref' => $data['bank_ref'] ?? $lockedPayment->bank_ref,
                ]);

                $order->is_paid = true;
                $order->payment_status = 'Paid';
                if ($order->order_status === 'pending') {
                    $order->order_status = 'confirmed';
                }
                $order->save();

                return true;
            }, 3);

            return $synchronized;
        }

        if (in_array($providerStatus, ['FAILED', 'DECLINED', 'CANCELLED', 'EXPIRED'], true)) {
            $payment->update(['status' => strtolower($providerStatus)]);
        } elseif ($providerStatus === 'APPROVED' && ! $approvedCodeIsValid) {
            Log::warning('ABA reported APPROVED with an unexpected payment status code.', [
                'payment_id' => $payment->id,
                'tran_id' => $payment->tran_id,
                'payment_status_code' => $providerStatusCode,
            ]);
        }

        return false;
    }

    private function ensureCustomerOwnsPayment(Payment $payment): void
    {
        $payment->loadMissing('order.customer');
        abort_unless((int) $payment->order?->customer?->user_id === (int) auth()->id(), 403);
    }

    private function ensureStaffOwnsPosPayment(Payment $payment): void
    {
        $payment->loadMissing('order');
        $roleName = strtolower((string) auth()->user()?->role?->role_name);
        abort_unless(in_array($roleName, ['admin', 'cashier'], true), 403);
        abort_unless($payment->provider === 'aba_payway' && $payment->order?->order_source === 'pos', 404);

        if ($roleName === 'cashier') {
            abort_unless((int) $payment->order?->cashier_id === (int) auth()->id(), 403);
        }
    }

    private function staffOrdersUrl(): string
    {
        $roleName = strtolower((string) auth()->user()?->role?->role_name);
        return $roleName === 'cashier' ? route('cashier.orders') : route('admin.orders.index');
    }
}
